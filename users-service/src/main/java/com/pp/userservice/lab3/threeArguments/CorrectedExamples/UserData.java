public class UserData {
    String userName;
    String password;
    String email;
    String phoneNumber;

    public UserData(String userName, String password, String email, String phoneNumber) {
        this.userName = userName;
        this.password = password;
        this.email = email;
        this.phoneNumber = phoneNumber;
    }
}
